package BasicConcepts;

public class DataTypeIntegerFloatChar {
    public static void main(String args[]){
        int a = 10;
        short b = 99;
        long c = 10012939009l;
        byte d = 1;

        float f_variable = 13.6654f;
        double d_variable = 16.2345234534533453345d;
        
        System.out.println("a = " + a);
        System.out.println("b = " + b);
        System.out.println("c = " + c);
        System.out.println("d = " + d);   

        System.out.println("float = " + f_variable);
        System.out.println("double = " + d_variable);
    }
}
